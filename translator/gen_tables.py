"""Write translator/faust/sctables.lib: scsynth's lookup tables, bit for bit.

    python3 translator/gen_tables.py

Mirrors common/Samp.cpp (SynthLibInit::FillTables): gSine[i] = (float)sin(i 2pi/8192)
computed in double, gInvSine[i] = (float)(1.0 / gSine[i]) with kBadValue (1e20) at the
zeros, and gSineWavetable (SignalAsWavetable, float arithmetic). Faust computing these in
float differs in the last bit, which near the zeros of the BLIT kernel is amplified ~2000x.
"""
from pathlib import Path

import numpy as np

N = 8192
BAD = np.float32(1e20)
OUT = Path(__file__).parent / "faust" / "sctables.lib"


def tables():
    i = np.arange(N + 1, dtype=np.float64)
    sine = np.sin(i * (2 * np.pi / N)).astype(np.float32)
    with np.errstate(divide="ignore"):
        inv = (1.0 / sine.astype(np.float64)).astype(np.float32)
    bad = [0, N // 2, N] + [j for k in range(1, 9) for j in (k, N - k, N // 2 - k, N // 2 + k)]
    inv[bad] = BAD
    s = sine[:N]
    nxt = np.concatenate([s[1:], s[:1]])  # last pair wraps to in[0]
    w0 = (np.float32(2) * s - nxt).astype(np.float32)
    w1 = (nxt - s).astype(np.float32)
    return sine, inv, w0, w1


def literal(a):
    return ", ".join(np.format_float_positional(v, unique=True) if abs(v) >= 1e-4 or v == 0
                     else np.format_float_scientific(v, unique=True) for v in a)


if __name__ == "__main__":
    sine, inv, w0, w1 = tables()
    OUT.write_text(
        "// Generated by translator/gen_tables.py: scsynth's tables (common/Samp.cpp). Do not edit.\n"
        f"sine = waveform{{{literal(sine)}}};\n"
        f"cosecant = waveform{{{literal(inv)}}};\n"
        f"sinew0 = waveform{{{literal(w0)}}};\n"
        f"sinew1 = waveform{{{literal(w1)}}};\n")
    print(f"{OUT} ({OUT.stat().st_size // 1024} KB)")
